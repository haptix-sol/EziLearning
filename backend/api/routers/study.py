@router.post("/days/{day_id}/complete")
def complete_day(
    day_id: str,
    current_user: CurrentUser,
    db: Session = Depends(get_db),
):
    """Mark a day as complete and award XP."""
    day = db.query(DayPlan).join(StudyPlan).filter(
        DayPlan.id == day_id,
        StudyPlan.user_id == current_user.id,
    ).first()
    if not day:
        raise NotFoundError("Day not found")
    existing = db.query(DayPlanCompletion).filter(
        DayPlanCompletion.user_id == current_user.id,
        DayPlanCompletion.day_plan_id == day_id,
    ).first()
    if existing:
        return {"message": "Already completed", "xp": existing.xp_earned}
    xp = 10 + (day.level * 5)
    topic_keys = all_topic_keys_for_day(day.topics)
    bonus = 0
    if topic_keys:
        done = db.query(VisualLessonTopicProgress).filter(
            VisualLessonTopicProgress.user_id == current_user.id,
            VisualLessonTopicProgress.day_plan_id == day_id,
            VisualLessonTopicProgress.topic_key.in_(topic_keys),
            VisualLessonTopicProgress.completed.is_(True),
        ).count()
        if done >= len(topic_keys):
            bonus = 5
            xp += bonus

    completion = DayPlanCompletion(user_id=current_user.id, day_plan_id=day_id, xp_earned=xp)
    db.add(completion)
    # Update user level
    ul = db.query(UserLevel).filter(UserLevel.user_id == current_user.id).first()
    if not ul:
        ul = UserLevel(user_id=current_user.id)
        db.add(ul)
        db.flush()
    ul.xp += xp
    today = date.today()
    if ul.last_activity_date:
        last = ul.last_activity_date.date() if hasattr(ul.last_activity_date, 'date') else ul.last_activity_date
        if isinstance(last, datetime):
            last = last.date()
        if (today - last).days == 1:
            ul.streak_days += 1
        elif (today - last).days > 1:
            ul.streak_days = 1
    else:
        ul.streak_days = 1
    ul.last_activity_date = datetime.now(timezone.utc)
    # Level up
    while ul.xp >= ul.xp_to_next_level:
        ul.xp -= ul.xp_to_next_level
        ul.level += 1
        ul.xp_to_next_level = int(ul.xp_to_next_level * 1.5)
    db.commit()
    return {"message": "Completed", "xp": xp, "level": ul.level, "visual_bonus_xp": bonus}


@router.get("/level", response_model=LevelResponse)
def get_level(current_user: CurrentUser, db: Session = Depends(get_db)):
    """Get user's level and XP progress."""
    ul = db.query(UserLevel).filter(UserLevel.user_id == current_user.id).first()
    if not ul:
        ul = UserLevel(user_id=current_user.id)
        db.add(ul)
        db.commit()
        db.refresh(ul)
    progress = (ul.xp / ul.xp_to_next_level * 100) if ul.xp_to_next_level else 0
    return LevelResponse(
        level=ul.level,
        xp=ul.xp,
        xp_to_next_level=ul.xp_to_next_level,
        progress_percent=round(progress, 1),
        streak_days=ul.streak_days,
    )


@router.get("/badges")
def get_earned_badges(current_user: CurrentUser, db: Session = Depends(get_db)):
    """Get role badges earned by completing study plans (all days done)."""
    goals = (
        db.query(UserGoal)
        .filter(
            UserGoal.user_id == current_user.id,
            UserGoal.study_plan_id.isnot(None),
        )
        .all()
    )
    badges = []
    for g in goals:
        day_ids = [r[0] for r in db.query(DayPlan.id).filter(DayPlan.study_plan_id == g.study_plan_id).all()]
        total = len(day_ids)
        if total == 0:
            continue
        completed = db.query(DayPlanCompletion).filter(
            DayPlanCompletion.user_id == current_user.id,
            DayPlanCompletion.day_plan_id.in_(day_ids),
        ).count()
        if completed >= total:
            role = db.query(TrendingRole).filter(TrendingRole.id == g.target_role_id).first() if g.target_role_id else None
            name = role.name if role else (g.goal_text or "Completed")
            badges.append({"role_name": name, "goal_id": g.id})
    return {"badges": badges}
