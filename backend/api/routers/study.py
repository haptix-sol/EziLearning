@router.get("/days/{day_id}/notes")
def get_day_notes(day_id: str, current_user: CurrentUser, db: Session = Depends(get_db)):
    """Return study notes for a day. Uses cached notes if already generated, otherwise generates and stores."""
    day = db.query(DayPlan).join(StudyPlan).filter(
        DayPlan.id == day_id,
        StudyPlan.user_id == current_user.id,
    ).first()
    if not day:
        raise NotFoundError("Day not found")
    # Return cached notes if already generated. Include animation_url when topics match.
    animation_filename = match_animation(day.topics, day.title)
    animation_url = f"/animations/{animation_filename}" if animation_filename else None
    if day.notes and day.notes.strip():
        return {"notes": day.notes, "topics": day.topics or [], "animation_url": animation_url}
    # Generate and store
    topics = day.topics or ["General study"]
    notes_parts = []
    for t in topics:
        notes_parts.append(generate_notes_for_topic(t, day.title))
    full_notes = "\n\n---\n\n".join(notes_parts)
    day.notes = full_notes
    db.commit()
    return {"notes": full_notes, "topics": topics, "animation_url": animation_url}


def _get_or_generate_notes(day: DayPlan, db: Session) -> str:
    """Get cached notes or generate and store. Returns notes content."""
    if day.notes and day.notes.strip():
        return day.notes
    topics = day.topics or ["General study"]
    notes_parts = [generate_notes_for_topic(t, day.title) for t in topics]
    full_notes = "\n\n---\n\n".join(notes_parts)
    day.notes = full_notes
    db.commit()
    return full_notes


